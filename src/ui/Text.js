/**
 * Draw a string using the bitmap font.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x        top-left x
 * @param {number} y        top-left y
 * @param {string} color    fill color
 * @param {number} scale    pixel size (default 2 → 10×14 per char)
 */
export function drawText(ctx, text, x, y, color = '#ffffff', scale = 2) {
  ctx.fillStyle = color;
  const charW = 5 * scale;
  const charGap = scale;   // 1 px gap between chars
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const bitmap = FONT[ch] || FONT[' '];
    for (let row = 0; row < 7; row++) {
      const bits = bitmap[row];
      for (let col = 0; col < 5; col++) {
        if (bits & (1 << (4 - col))) {
          ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
        }
      }
    }
    cx += charW + charGap;
  }
}

/**
 * Measure text width in pixels.
 */
export function measureText(text, scale = 2) {
  return text.length * (5 * scale + scale);
}
